#!/usr/bin/env python3
"""Automated verification suite asserting Falco eBPF and K8s Audit log detections.

This test harness executes attack emulations and asserts that target telemetry
and security alerts are generated by:
1. Falco runtime engine (eBPF syscall events: T1609, T1613, T1611)
2. Kubernetes Control Plane Audit engine (API server events: T1098.004, T1609)

Supports both:
- Live cluster verification: executes commands via kubectl and polls live logs.
- Offline / Synthetic verification: verifies detection parsers and rule evaluations
  against synthetic telemetry and verified sample alerts.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path
from typing import Dict, List, Optional, Tuple

# Enable relative import of detection module
REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from detections.k8s_audit_rules import AuditLogDetector


def run_cmd(cmd: str, timeout: int = 60) -> subprocess.CompletedProcess[str]:
    """Execute a shell command with timeout and captured output."""
    try:
        return subprocess.run(
            cmd,
            shell=True,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        return subprocess.CompletedProcess(
            args=cmd,
            returncode=124,
            stdout="",
            stderr=f"Command timed out after {timeout} seconds: {exc}",
        )


class TestHarness:
    """Detection validation harness managing live and offline test cases."""

    def __init__(
        self,
        cluster_name: str = "k8s-detection-lab",
        falco_namespace: str = "falco",
        poll_interval: float = 2.0,
        max_retries: int = 15,
        verbose: bool = False,
    ) -> None:
        self.cluster_name = cluster_name
        self.falco_namespace = falco_namespace
        self.poll_interval = poll_interval
        self.max_retries = max_retries
        self.verbose = verbose
        self.audit_detector = AuditLogDetector()
        self.results: List[Tuple[str, str, bool, str]] = []

    def log(self, msg: str) -> None:
        print(f"[*] {msg}")

    def log_pass(self, msg: str) -> None:
        print(f"[+] PASS: {msg}")

    def log_fail(self, msg: str) -> None:
        print(f"[-] FAIL: {msg}")

    def log_warn(self, msg: str) -> None:
        print(f"[!] {msg}")

    # =========================================================================
    # Live Telemetry Retrieval Helpers
    # =========================================================================

    def fetch_falco_logs(self, tail: int = 100) -> str:
        """Fetch latest logs from Falco daemonset pod."""
        cmd = (
            f"kubectl logs -l app.kubernetes.io/name=falco -n {self.falco_namespace} "
            f"-c falco --tail={tail}"
        )
        res = run_cmd(cmd)
        if self.verbose and res.stdout:
            print(f"[DEBUG Falco Logs]\n{res.stdout[-500:]}\n")
        return res.stdout or ""

    def fetch_audit_log_content(self) -> str:
        """Fetch control-plane audit log from host mount or docker exec fallback."""
        host_log_candidates = [
            REPO_ROOT / "logs" / "audit" / "kube-audit.log",
            Path("/var/log/kubernetes/kube-audit.log"),
        ]
        for p in host_log_candidates:
            if p.exists():
                try:
                    return p.read_text(encoding="utf-8", errors="replace")
                except Exception:
                    pass

        # Fallback to docker exec into kind control-plane container
        container = f"{self.cluster_name}-control-plane"
        cmd = f"docker exec {container} cat /var/log/kubernetes/kube-audit.log 2>/dev/null || true"
        res = run_cmd(cmd)
        return res.stdout or ""

    def poll_falco_for_signature(self, signature: str, description: str) -> bool:
        """Poll Falco logs until expected alert signature appears or timeout expires."""
        self.log(f"Polling Falco telemetry for signature '{signature}'...")
        for attempt in range(1, self.max_retries + 1):
            logs = self.fetch_falco_logs(tail=200)
            if signature in logs:
                self.log_pass(f"{description} detected on poll attempt {attempt}.")
                return True
            time.sleep(self.poll_interval)
        self.log_fail(f"{description} not detected within {self.max_retries * self.poll_interval:.0f}s timeout.")
        return False

    def poll_audit_for_rule(self, rule_id: str, description: str) -> bool:
        """Poll K8s Audit log until specified rule alert is triggered."""
        self.log(f"Polling K8s Audit log for rule '{rule_id}'...")
        for attempt in range(1, self.max_retries + 1):
            log_content = self.fetch_audit_log_content()
            if log_content:
                lines = log_content.strip().splitlines()
                alerts = list(self.audit_detector.process_stream(lines[-200:]))
                if any(a.rule_id == rule_id for a in alerts):
                    self.log_pass(f"{description} detected on poll attempt {attempt}.")
                    return True
            time.sleep(self.poll_interval)
        self.log_fail(f"{description} not detected within {self.max_retries * self.poll_interval:.0f}s timeout.")
        return False

    # =========================================================================
    # Live Cluster Tests
    # =========================================================================

    def test_live_interactive_shell(self) -> bool:
        """Live Test 1: MITRE T1609 (Interactive Shell)."""
        test_name = "T1609: Interactive Shell in Workload"
        self.log(f"Starting {test_name}...")
        try:
            run_cmd("kubectl run test-shell-pod --image=busybox:latest --restart=Never -n default -- sleep 3600")
            run_cmd("kubectl wait --for=condition=Ready pod/test-shell-pod -n default --timeout=30s")
            run_cmd("kubectl exec test-shell-pod -n default -- /bin/sh -c 'id && cat /etc/passwd'")

            passed = self.poll_falco_for_signature(
                "K8S_CONTAINER_SHELL_SPAWNED",
                "T1609 Container Shell Spawn",
            )
            self.results.append(("Live", "T1609", passed, test_name))
            return passed
        finally:
            run_cmd("kubectl delete pod test-shell-pod -n default --ignore-not-found=true --grace-period=0 --force 2>/dev/null")

    def test_live_token_access(self) -> bool:
        """Live Test 2: MITRE T1613 (Token Theft)."""
        test_name = "T1613: Service Account Token Harvesting"
        self.log(f"Starting {test_name}...")
        try:
            run_cmd("kubectl run test-token-pod --image=busybox:latest --restart=Never -n default -- sleep 3600")
            run_cmd("kubectl wait --for=condition=Ready pod/test-token-pod -n default --timeout=30s")
            run_cmd("kubectl exec test-token-pod -n default -- cat /var/run/secrets/kubernetes.io/serviceaccount/token 2>/dev/null || true")

            passed = self.poll_falco_for_signature(
                "K8S_SERVICE_ACCOUNT_TOKEN_READ",
                "T1613 Token Read Detection",
            )
            self.results.append(("Live", "T1613", passed, test_name))
            return passed
        finally:
            run_cmd("kubectl delete pod test-token-pod -n default --ignore-not-found=true --grace-period=0 --force 2>/dev/null")

    def test_live_container_escape(self) -> bool:
        """Live Test 3: MITRE T1611 (HostPath Escape Surface)."""
        test_name = "T1611: Sensitive HostPath Mount Escape Surface"
        self.log(f"Starting {test_name}...")
        manifest = REPO_ROOT / "attacks" / "payloads" / "breakout-pod.yaml"
        try:
            run_cmd(f"kubectl apply -f {manifest}")
            run_cmd("kubectl wait --for=condition=Ready pod/breakout-pod -n default --timeout=30s || true")
            run_cmd("kubectl exec breakout-pod -n default -- head -n 1 /host/proc/version 2>/dev/null || true")

            passed = self.poll_falco_for_signature(
                "K8S_CONTAINER_HOST_ESCAPE_SURFACE",
                "T1611 Host Escape Surface Detection",
            )
            self.results.append(("Live", "T1611", passed, test_name))
            return passed
        finally:
            run_cmd("kubectl delete pod breakout-pod -n default --ignore-not-found=true --grace-period=0 --force 2>/dev/null")

    def test_live_rogue_rbac(self) -> bool:
        """Live Test 4: MITRE T1098.004 (Rogue ClusterRoleBinding)."""
        test_name = "T1098.004: Rogue ClusterRoleBinding Privilege Escalation"
        self.log(f"Starting {test_name}...")
        manifest = REPO_ROOT / "attacks" / "payloads" / "rogue-rbac.yaml"
        try:
            run_cmd(f"kubectl apply -f {manifest}")
            passed = self.poll_audit_for_rule(
                "K8S-AUDIT-001",
                "T1098.004 Rogue ClusterRoleBinding Audit Detection",
            )
            self.results.append(("Live", "T1098.004", passed, test_name))
            return passed
        finally:
            run_cmd("kubectl delete clusterrolebinding rogue-admin --ignore-not-found=true 2>/dev/null")

    # =========================================================================
    # Offline / Synthetic Verification
    # =========================================================================

    def test_offline_sample_alerts(self) -> bool:
        """Verify schema and validity of sample_alerts.json."""
        test_name = "Offline Schema: sample_alerts.json Validation"
        sample_path = REPO_ROOT / "validation" / "sample_alerts.json"
        try:
            assert sample_path.exists(), f"Missing file: {sample_path}"
            with open(sample_path, "r", encoding="utf-8") as f:
                data = json.load(f)

            assert "falco_runtime_alerts" in data, "Missing falco_runtime_alerts"
            assert "control_plane_audit_alerts" in data, "Missing control_plane_audit_alerts"

            # Validate Falco events
            for alert in data["falco_runtime_alerts"]:
                assert "rule" in alert
                assert "output" in alert
                assert "output_fields" in alert
                # Check output JSON parses
                parsed_out = json.loads(alert["output"])
                assert "event" in parsed_out
                assert "severity" in parsed_out
                assert "mitre" in parsed_out

            # Validate Audit alerts
            for alert in data["control_plane_audit_alerts"]:
                assert "rule_id" in alert
                assert "mitre_technique" in alert
                assert "actor_username" in alert
                assert "verb" in alert

            self.log_pass(f"{test_name} passed successfully.")
            self.results.append(("Offline", "Schema", True, test_name))
            return True
        except Exception as exc:
            self.log_fail(f"{test_name} failed: {exc}")
            self.results.append(("Offline", "Schema", False, f"{test_name}: {exc}"))
            return False

    def test_offline_audit_detection_engine(self) -> bool:
        """Unit test AuditLogDetector against synthetic K8s API audit events."""
        test_name = "Offline Engine: AuditLogDetector Rule Logic"
        try:
            # 1. Test Rogue ClusterRoleBinding Event
            event_rbac = {
                "stage": "ResponseComplete",
                "verb": "create",
                "stageTimestamp": "2026-10-11T12:00:00.000000Z",
                "auditID": "test-audit-id-1",
                "user": {"username": "adversary", "groups": ["system:authenticated"]},
                "sourceIPs": ["10.0.0.99"],
                "userAgent": "kubectl/v1.30.0",
                "objectRef": {
                    "resource": "clusterrolebindings",
                    "apiGroup": "rbac.authorization.k8s.io",
                    "name": "rogue-admin",
                },
                "requestObject": {
                    "roleRef": {"kind": "ClusterRole", "name": "cluster-admin"},
                    "subjects": [{"kind": "ServiceAccount", "name": "default", "namespace": "default"}],
                },
            }
            alerts_rbac = self.audit_detector.evaluate_line(json.dumps(event_rbac))
            assert len(alerts_rbac) == 1, f"Expected 1 alert, got {len(alerts_rbac)}"
            assert alerts_rbac[0].rule_id == "K8S-AUDIT-001"
            assert alerts_rbac[0].mitre_technique == "T1098.004"

            # 2. Test Pod Exec Event
            event_exec = {
                "stage": "ResponseComplete",
                "verb": "create",
                "stageTimestamp": "2026-10-11T12:01:00.000000Z",
                "auditID": "test-audit-id-2",
                "user": {"username": "admin-user", "groups": ["system:masters"]},
                "sourceIPs": ["10.0.0.100"],
                "userAgent": "kubectl/v1.30.0",
                "objectRef": {
                    "resource": "pods",
                    "subresource": "exec",
                    "name": "payment-service",
                    "namespace": "default",
                },
                "requestURI": "/api/v1/namespaces/default/pods/payment-service/exec",
            }
            alerts_exec = self.audit_detector.evaluate_line(json.dumps(event_exec))
            assert len(alerts_exec) == 1, f"Expected 1 exec alert, got {len(alerts_exec)}"
            assert alerts_exec[0].rule_id == "K8S-AUDIT-002"
            assert alerts_exec[0].mitre_technique == "T1609"

            # 3. Test HostPath Pod Creation Event
            event_hostpath = {
                "stage": "ResponseComplete",
                "verb": "create",
                "stageTimestamp": "2026-10-11T12:02:00.000000Z",
                "auditID": "test-audit-id-3",
                "user": {"username": "attacker", "groups": ["system:authenticated"]},
                "sourceIPs": ["10.0.0.101"],
                "userAgent": "kubectl/v1.30.0",
                "objectRef": {
                    "resource": "pods",
                    "name": "breakout-pod",
                    "namespace": "default",
                },
                "requestObject": {
                    "spec": {
                        "volumes": [{"name": "proc", "hostPath": {"path": "/proc"}}],
                        "containers": [{"name": "breakout", "image": "busybox"}],
                    }
                },
            }
            alerts_hostpath = self.audit_detector.evaluate_line(json.dumps(event_hostpath))
            assert len(alerts_hostpath) == 1, f"Expected 1 hostPath alert, got {len(alerts_hostpath)}"
            assert alerts_hostpath[0].rule_id == "K8S-AUDIT-004"
            assert alerts_hostpath[0].mitre_technique == "T1611"

            self.log_pass(f"{test_name} passed successfully.")
            self.results.append(("Offline", "AuditEngine", True, test_name))
            return True
        except Exception as exc:
            self.log_fail(f"{test_name} failed: {exc}")
            self.results.append(("Offline", "AuditEngine", False, f"{test_name}: {exc}"))
            return False

    def print_summary(self) -> int:
        """Print test suite summary table and return exit code."""
        print("\n" + "=" * 70)
        print("K8S-GUARD TEST EXECUTION SUMMARY")
        print("=" * 70)
        total = len(self.results)
        passed = sum(1 for _, _, p, _ in self.results if p)
        failed = total - passed

        for mode, tag, result, name in self.results:
            status = "PASS" if result else "FAIL"
            print(f"[{status:4s}] [{mode:7s}] [{tag:9s}] {name}")

        print("-" * 70)
        print(f"Total Tests: {total} | Passed: {passed} | Failed: {failed}")
        print("=" * 70 + "\n")
        return 0 if failed == 0 else 1


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Automated Test Suite for K8s Runtime & Control Plane Detections"
    )
    parser.add_argument(
        "--live",
        action="store_true",
        help="Execute live cluster attack emulations and verify alert firing",
    )
    parser.add_argument(
        "--offline",
        action="store_true",
        help="Run offline verification of detection rules and sample alerts",
    )
    parser.add_argument(
        "--scenario",
        type=int,
        choices=[1, 2, 3, 4],
        help="Run a specific live scenario number (1: T1609, 2: T1613, 3: T1611, 4: T1098.004)",
    )
    parser.add_argument(
        "--cluster-name",
        type=str,
        default="k8s-detection-lab",
        help="Target Kind cluster name (default: k8s-detection-lab)",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Print verbose telemetry logs during polling",
    )
    args = parser.parse_args()

    # Default to offline if neither flag is explicitly passed and cluster is not running
    run_live = args.live or (args.scenario is not None)
    run_offline = args.offline or (not run_live)

    harness = TestHarness(cluster_name=args.cluster_name, verbose=args.verbose)

    if run_offline:
        harness.log("Executing offline detection verification...")
        harness.test_offline_sample_alerts()
        harness.test_offline_audit_detection_engine()

    if run_live:
        harness.log(f"Executing live cluster tests on cluster '{args.cluster_name}'...")
        if args.scenario == 1 or args.scenario is None:
            harness.test_live_interactive_shell()
        if args.scenario == 2 or args.scenario is None:
            harness.test_live_token_access()
        if args.scenario == 3 or args.scenario is None:
            harness.test_live_container_escape()
        if args.scenario == 4 or args.scenario is None:
            harness.test_live_rogue_rbac()

    return harness.print_summary()


if __name__ == "__main__":
    sys.exit(main())
